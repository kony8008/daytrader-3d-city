// DayTrader 3D City - Interactive Cesium Front-end
const WS_URL = window.location.protocol === 'https:' ? `wss://${window.location.host}/ws` : `ws://${window.location.hostname || '127.0.0.1'}:8765`;

// City Coordinates (Wall St District setup)
const CITY_LON = -74.0090;
const CITY_LAT = 40.7070;
const CITY_ALT = 0.0;

// Initialize Cesium Viewer
const viewer = new Cesium.Viewer('cesiumContainer', {
  terrainProvider: Cesium.createWorldTerrain ? Cesium.createWorldTerrain() : undefined,
  animation: false,
  timeline: false,
  baseLayerPicker: false,
  geocoder: false,
  homeButton: false,
  sceneModePicker: false,
  navigationHelpButton: false,
  infoBox: false,
  fullscreenButton: false,
  scene3DOnly: true
});

viewer.scene.globe.enableLighting = true;
viewer.scene.globe.depthTestAgainstTerrain = true;

// Load procedural 3D city model generated by Blender
let cityModelEntity = null;
const modelMatrix = Cesium.Transforms.eastNorthUpToFixedFrame(
  Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT, CITY_ALT)
);

try {
  cityModelEntity = viewer.scene.primitives.add(Cesium.Model.fromGltf({
    url: './city.glb',
    modelMatrix: modelMatrix,
    scale: 1.0,
    minimumPixelSize: 128
  }));
} catch (e) {
  console.warn("Could not load city.glb directly, fallback procedural display", e);
}

// Initial Camera Orientation
function focusDowntown() {
  viewer.camera.flyTo({
    destination: Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT - 0.006, 650.0),
    orientation: {
      heading: Cesium.Math.toRadians(0.0),
      pitch: Cesium.Math.toRadians(-35.0),
      roll: 0.0
    },
    duration: 2.0
  });
}
focusDowntown();

// Auto Flyover Logic
let isFlying = false;
let flyHeading = 0.0;
function toggleFlyover() {
  isFlying = !isFlying;
  const btn = document.getElementById('flyBtn');
  if (btn) btn.textContent = isFlying ? 'Stop Flyover' : 'Flyover Auto';
}

viewer.clock.onTick.addEventListener(() => {
  if (isFlying) {
    flyHeading += 0.0025;
    const distance = 800.0;
    const pitch = Cesium.Math.toRadians(-28.0);
    viewer.camera.lookAt(
      Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT, 50.0),
      new Cesium.HeadingPitchRange(flyHeading, pitch, distance)
    );
  }
});

function toggleWireframe() {
  viewer.scene.globe.show = !viewer.scene.globe.show;
}

// Trader Fleet Management
const traderEntities = {};

function createOrUpdateTrader(trader) {
  const position = Cesium.Cartesian3.fromDegrees(trader.lon, trader.lat, trader.alt || 40.0);
  const isProfit = trader.pnl >= 0;
  const color = isProfit ? Cesium.Color.fromCssColorString('#22c55e') : Cesium.Color.fromCssColorString('#ef4444');

  if (!traderEntities[trader.id]) {
    // New trader node
    traderEntities[trader.id] = viewer.entities.add({
      id: trader.id,
      position: position,
      point: {
        pixelSize: 10,
        color: color,
        outlineColor: Cesium.Color.WHITE,
        outlineWidth: 2
      },
      label: {
        text: `${trader.name}\n${trader.symbol} | ${trader.strategy}\n${isProfit ? '+' : ''}$${trader.pnl.toFixed(2)}`,
        font: '11px sans-serif',
        style: Cesium.LabelStyle.FILL_AND_OUTLINE,
        outlineWidth: 2,
        verticalOrigin: Cesium.VerticalOrigin.BOTTOM,
        pixelOffset: new Cesium.Cartesian2(0, -14),
        showBackground: true,
        backgroundColor: new Cesium.Color(0.05, 0.08, 0.15, 0.85)
      }
    });
  } else {
    // Update live trader
    const entity = traderEntities[trader.id];
    entity.position = position;
    entity.point.color = color;
    entity.label.text = `${trader.name}\n${trader.symbol} | ${trader.strategy}\n${isProfit ? '+' : ''}$${trader.pnl.toFixed(2)}`;
  }
}

// Click to inspect trader
const handler = new Cesium.ScreenSpaceEventHandler(viewer.scene.canvas);
handler.setInputAction((movement) => {
  const pickedObject = viewer.scene.pick(movement.position);
  if (Cesium.defined(pickedObject) && pickedObject.id && pickedObject.id.id) {
    const id = pickedObject.id.id;
    if (traderEntities[id]) {
      const entity = pickedObject.id;
      document.getElementById('insp-name').textContent = id;
    }
  }
}, Cesium.ScreenSpaceEventType.LEFT_CLICK);

// Update HUD summary
function updateHUD(summary, traders) {
  if (!summary) return;
  document.getElementById('totalTraders').textContent = `${summary.totalTraders} Bots`;
  document.getElementById('totalEquity').textContent = `$${summary.totalEquity.toLocaleString(undefined, {minimumFractionDigits: 2})}`;
  
  const pnlEl = document.getElementById('activePnL');
  const isPos = summary.activePnL >= 0;
  pnlEl.textContent = `${isPos ? '+' : ''}$${summary.activePnL.toLocaleString(undefined, {minimumFractionDigits: 2})}`;
  pnlEl.className = isPos ? 'green' : 'red';
  
  document.getElementById('winRate').textContent = `${summary.winRate}%`;
  document.getElementById('sharpe').textContent = `${summary.avgSharpe}`;

  // Update inspector with top performer
  if (traders && traders.length > 0) {
    const top = traders[0];
    document.getElementById('insp-name').textContent = top.name;
    document.getElementById('insp-strat').textContent = top.strategy;
    document.getElementById('insp-sym').textContent = top.symbol;
    const inspPnl = document.getElementById('insp-pnl');
    inspPnl.textContent = `${top.pnl >= 0 ? '+' : ''}$${top.pnl.toFixed(2)}`;
    inspPnl.className = top.pnl >= 0 ? 'green' : 'red';
    document.getElementById('insp-conf').textContent = `${top.confidence}%`;
  }
}

// Connect to WebSocket Server
function connectWebSocket() {
  const socket = new WebSocket(WS_URL);

  socket.onopen = () => {
    console.log("Connected to 3D Trader Fleet live feed:", WS_URL);
  };

  socket.onmessage = (event) => {
    try {
      const data = JSON.parse(event.data);
      if (data.type === 'FLEET_UPDATE' && Array.isArray(data.traders)) {
        data.traders.forEach(createOrUpdateTrader);
        updateHUD(data.summary, data.traders);
      }
    } catch (err) {
      console.error("Error processing trader update", err);
    }
  };

  socket.onclose = () => {
    console.log("WebSocket closed, retrying in 3 seconds...");
    setTimeout(connectWebSocket, 3000);
  };

  socket.onerror = (err) => {
    console.warn("WebSocket stream notice:", err.message || err);
  };
}

connectWebSocket();
