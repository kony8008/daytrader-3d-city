// DayTrader 3D City - Interactive Cesium Front-end
const WS_URL = window.location.protocol === 'https:' 
  ? `wss://${window.location.host}/ws` 
  : `ws://${window.location.hostname || '127.0.0.1'}:8765`;

// City Coordinates (Wall St District setup)
const CITY_LON = -74.0090;
const CITY_LAT = 40.7070;
const CITY_ALT = 0.0;

// Setup OpenStreetMap default base layer so globe always renders without Ion token
const imageryProvider = new Cesium.OpenStreetMapImageryProvider({
  url: 'https://tile.openstreetmap.org/'
});

// Initialize Cesium Viewer
const viewer = new Cesium.Viewer('cesiumContainer', {
  imageryProvider: imageryProvider,
  baseLayer: new Cesium.ImageryLayer(imageryProvider),
  animation: false,
  timeline: false,
  baseLayerPicker: false,
  geocoder: false,
  homeButton: false,
  sceneModePicker: false,
  navigationHelpButton: false,
  infoBox: false,
  fullscreenButton: false,
  selectionIndicator: false,
  scene3DOnly: true
});

viewer.scene.globe.enableLighting = true;
viewer.scene.globe.depthTestAgainstTerrain = false;

// Load procedural 3D city model generated by Blender as an Entity with URI
const cityPosition = Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT, CITY_ALT);

const cityEntity = viewer.entities.add({
  name: 'Financial District 3D City',
  position: cityPosition,
  model: {
    uri: './city.glb',
    minimumPixelSize: 128,
    maximumScale: 20000,
    scale: 1.0,
    runAnimations: false,
    shadows: Cesium.ShadowMode.ENABLED
  }
});

// Initial Camera Orientation
function focusDowntown() {
  viewer.camera.flyTo({
    destination: Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT - 0.0055, 620.0),
    orientation: {
      heading: Cesium.Math.toRadians(0.0),
      pitch: Cesium.Math.toRadians(-32.0),
      roll: 0.0
    },
    duration: 2.0
  });
}

// Initial fly to downtown after load
setTimeout(focusDowntown, 500);

// Auto Flyover Logic
let isFlying = false;
let flyHeading = 0.0;
function toggleFlyover() {
  isFlying = !isFlying;
  const btn = document.getElementById('flyBtn');
  if (btn) btn.textContent = isFlying ? 'Stop Flyover' : 'Flyover Auto';
}

viewer.clock.onTick.addEventListener(() => {
  if (isFlying) {
    flyHeading += 0.003;
    const distance = 750.0;
    const pitch = Cesium.Math.toRadians(-26.0);
    viewer.camera.lookAt(
      Cesium.Cartesian3.fromDegrees(CITY_LON, CITY_LAT, 45.0),
      new Cesium.HeadingPitchRange(flyHeading, pitch, distance)
    );
  }
});

function toggleWireframe() {
  viewer.scene.globe.show = !viewer.scene.globe.show;
}

// Trader Fleet Management
const traderEntities = {};

function createOrUpdateTrader(trader) {
  const position = Cesium.Cartesian3.fromDegrees(trader.lon, trader.lat, trader.alt || 40.0);
  const isProfit = trader.pnl >= 0;
  const color = isProfit 
    ? Cesium.Color.fromCssColorString('#22c55e') 
    : Cesium.Color.fromCssColorString('#ef4444');

  if (!traderEntities[trader.id]) {
    // New trader node
    traderEntities[trader.id] = viewer.entities.add({
      id: trader.id,
      position: position,
      point: {
        pixelSize: 12,
        color: color,
        outlineColor: Cesium.Color.WHITE,
        outlineWidth: 2,
        disableDepthTestDistance: Number.POSITIVE_INFINITY
      },
      label: {
        text: `${trader.name}\n${trader.symbol} | ${trader.strategy}\n${isProfit ? '+' : ''}$${trader.pnl.toFixed(2)}`,
        font: 'bold 11px sans-serif',
        style: Cesium.LabelStyle.FILL_AND_OUTLINE,
        outlineWidth: 2,
        verticalOrigin: Cesium.VerticalOrigin.BOTTOM,
        pixelOffset: new Cesium.Cartesian2(0, -16),
        showBackground: true,
        backgroundColor: new Cesium.Color(0.05, 0.08, 0.15, 0.88),
        disableDepthTestDistance: Number.POSITIVE_INFINITY
      }
    });
  } else {
    // Update live trader
    const entity = traderEntities[trader.id];
    entity.position = position;
    entity.point.color = color;
    entity.label.text = `${trader.name}\n${trader.symbol} | ${trader.strategy}\n${isProfit ? '+' : ''}$${trader.pnl.toFixed(2)}`;
  }
}

// Click to inspect trader
const handler = new Cesium.ScreenSpaceEventHandler(viewer.scene.canvas);
handler.setInputAction((movement) => {
  const pickedObject = viewer.scene.pick(movement.position);
  if (Cesium.defined(pickedObject) && pickedObject.id && pickedObject.id.id) {
    const id = pickedObject.id.id;
    if (traderEntities[id]) {
      document.getElementById('insp-name').textContent = id;
    }
  }
}, Cesium.ScreenSpaceEventType.LEFT_CLICK);

// Update HUD summary
function updateHUD(summary, traders) {
  if (!summary) return;
  document.getElementById('totalTraders').textContent = `${summary.totalTraders} Bots`;
  document.getElementById('totalEquity').textContent = `$${summary.totalEquity.toLocaleString(undefined, {minimumFractionDigits: 2})}`;
  
  const pnlEl = document.getElementById('activePnL');
  const isPos = summary.activePnL >= 0;
  pnlEl.textContent = `${isPos ? '+' : ''}$${summary.activePnL.toLocaleString(undefined, {minimumFractionDigits: 2})}`;
  pnlEl.className = isPos ? 'green' : 'red';
  
  document.getElementById('winRate').textContent = `${summary.winRate}%`;
  document.getElementById('sharpe').textContent = `${summary.avgSharpe}`;

  // Update inspector with leader
  if (traders && traders.length > 0) {
    const top = traders[0];
    document.getElementById('insp-name').textContent = top.name;
    document.getElementById('insp-strat').textContent = top.strategy;
    document.getElementById('insp-sym').textContent = top.symbol;
    const inspPnl = document.getElementById('insp-pnl');
    inspPnl.textContent = `${top.pnl >= 0 ? '+' : ''}$${top.pnl.toFixed(2)}`;
    inspPnl.className = top.pnl >= 0 ? 'green' : 'red';
    document.getElementById('insp-conf').textContent = `${top.confidence}%`;
  }
}

// Connect to WebSocket Server with fallback mock simulation if standalone
function connectWebSocket() {
  let socket;
  try {
    socket = new WebSocket(WS_URL);
  } catch (e) {
    startFallbackSimulation();
    return;
  }

  socket.onopen = () => {
    console.log("Connected to 3D Trader Fleet live feed:", WS_URL);
  };

  socket.onmessage = (event) => {
    try {
      const data = JSON.parse(event.data);
      if (data.type === 'FLEET_UPDATE' && Array.isArray(data.traders)) {
        data.traders.forEach(createOrUpdateTrader);
        updateHUD(data.summary, data.traders);
      }
    } catch (err) {
      console.error("Error processing trader update", err);
    }
  };

  socket.onclose = () => {
    console.warn("WebSocket disconnected. Falling back to local autonomous client simulation...");
    startFallbackSimulation();
  };

  socket.onerror = () => {
    startFallbackSimulation();
  };
}

// Fallback simulator for GitHub Pages (where no local ws server is running)
let fallbackActive = false;
function startFallbackSimulation() {
  if (fallbackActive) return;
  fallbackActive = true;
  console.log("Running in autonomous client simulation mode (GitHub Pages ready)");

  const STRATEGIES = ["Scalping", "Momentum", "Grid Trading", "DCA", "Mean Reversion", "Swing"];
  const SYMBOLS = ["BTC/USDT", "ETH/USDT", "NVDA", "AAPL", "MSFT", "SPY", "SOL/USDT"];
  const simTraders = [];

  for (let i = 1; i <= 18; i++) {
    simTraders.push({
      id: `trader_${i < 10 ? '0' + i : i}`,
      name: i === 1 ? 'OpenFang-Leader' : `DeskBot-${i < 10 ? '0' + i : i}`,
      lon: CITY_LON + (Math.random() - 0.5) * 0.0035,
      lat: CITY_LAT + (Math.random() - 0.5) * 0.0035,
      alt: 15.0 + Math.random() * 65.0,
      symbol: SYMBOLS[Math.floor(Math.random() * SYMBOLS.length)],
      strategy: STRATEGIES[Math.floor(Math.random() * STRATEGIES.length)],
      pnl: parseFloat(((Math.random() - 0.3) * 350).toFixed(2)),
      equity: parseFloat((10000 + Math.random() * 850).toFixed(2)),
      winRate: parseFloat((58 + Math.random() * 24).toFixed(1)),
      sharpe: parseFloat((1.3 + Math.random() * 1.4).toFixed(2)),
      confidence: Math.floor(65 + Math.random() * 32)
    });
  }

  setInterval(() => {
    simTraders.forEach(t => {
      const delta = (Math.random() - 0.46) * 4.2;
      t.pnl = parseFloat((t.pnl + delta).toFixed(2));
      t.equity = parseFloat((t.equity + delta).toFixed(2));
      if (Math.random() < 0.06) {
        t.symbol = SYMBOLS[Math.floor(Math.random() * SYMBOLS.length)];
        t.confidence = Math.floor(70 + Math.random() * 28);
      }
      createOrUpdateTrader(t);
    });

    const summary = {
      totalTraders: simTraders.length,
      totalEquity: Math.round(simTraders.reduce((a, b) => a + b.equity, 0)),
      activePnL: parseFloat(simTraders.reduce((a, b) => a + b.pnl, 0).toFixed(2)),
      winRate: (simTraders.reduce((a, b) => a + b.winRate, 0) / simTraders.length).toFixed(1),
      avgSharpe: (simTraders.reduce((a, b) => a + b.sharpe, 0) / simTraders.length).toFixed(2)
    };
    updateHUD(summary, simTraders);
  }, 1000);
}

connectWebSocket();
